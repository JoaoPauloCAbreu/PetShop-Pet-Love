    private void limparCampos(){
        CPFTextField.setText("");
        RacaTextField.setText("");
        NomeTextField.setText("");
        IdadeTextField.setText("");
        SexoButton.clearSelection();
        EspecieComboBox.setSelectedIndex(-1);
    }
    
    private void HabilitarBotao(boolean a){
        SalvarButton.setVisible(a);
        CancelarButton.setVisible(a);
        NovoButton.setVisible(!a);
        EditarButton.setVisible(!a);
        ExcluirButton.setVisible(!a);
    }
    
    private void HabilitarCampos(boolean a){
    NomeTextField.setEnabled(a);
    RacaTextField.setEnabled(a);
    CPFTextField.setEnabled(a);
    IdadeTextField.setEnabled(a);
    FemeaRadioButton.setEnabled(a);
    MachoRadioButton.setEnabled(a);
    EspecieComboBox.setEnabled(a);
    }
    
    private void carregarTabela() {
    DefaultTableModel model = (DefaultTableModel) TabelaPets.getModel();
    model.setRowCount(0); 

    for (Pets c : DataBaseArrays.ArrayPets) {
        model.addRow(new Object[]{
            c.getNome(),
            c.getRaca(),
            c.getIdade(),
            c.getEspecie(),
            c.getTutor(),
            c.getSexo()
            
        });
    }
}
    
    private int SelecionarEspecie(String a){
    if(a.equals("Cachorro")){
        return 0;
    }
    else if(a.equals("Gato")){
        return 1;
    }
    else if(a.equals("Passaro")){
        return 2;
    }
    else{
        return 3;
    }
    
    }
    
    private void SelecionarSexo(String a){
        if (a.equals("Macho")) {
            MachoRadioButton.setSelected(true);
        } 
        else {
            FemeaRadioButton.setSelected(true);
        }   
    }
    
    private String SetandoSexo(){
    if (MachoRadioButton.isSelected()) {
            return "Macho";
        } 
    else if(FemeaRadioButton.isSelected()){
            return "Femea";
        }
    return "";
    }

