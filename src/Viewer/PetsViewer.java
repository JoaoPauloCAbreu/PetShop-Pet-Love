    private void ExcluirButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ExcluirButtonActionPerformed
        int Confirmacao = JOptionPane.showConfirmDialog(null, "Deseja Excluir?","Confirmação",JOptionPane.YES_NO_OPTION);
        if(Confirmacao == JOptionPane.YES_OPTION){
            int linha = TabelaPets.getSelectedRow();
            DefaultTableModel model = (DefaultTableModel) TabelaPets.getModel();
            DataBaseArrays.ArrayPets.remove(linha);
            model.removeRow(linha);
            LeitorEEscritor.Escrever(Path, DataBaseArrays.ArrayPets, new PetsCodec(), false);
            limparCampos();
        }// TODO add your handling code here:
    }//GEN-LAST:event_ExcluirButtonActionPerformed

    private void SalvarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SalvarButtonActionPerformed
        try{
            if(NomeTextField.getText().trim().isEmpty() || CPFTextField.getText().trim().isEmpty() || IdadeTextField.getText().trim().isEmpty() || RacaTextField.getText().trim().isEmpty() || EspecieComboBox.getSelectedIndex() == -1 || (!MachoRadioButton.isSelected() && !FemeaRadioButton.isSelected())){
                JOptionPane.showMessageDialog(null,"Campos Vazio, digite algo!", "Campos Vazios",JOptionPane.WARNING_MESSAGE);
            }
            else{
            
                if(Tipo.equals("novo")){
                    String Nome = NomeTextField.getText().trim();
                    String CPF = CPFTextField.getText().trim();
                    int idade = Integer.parseInt(IdadeTextField.getText().trim());
                    String Raca = RacaTextField.getText().trim();
                    String Especie = (String) EspecieComboBox.getSelectedItem();
                    String Sexo = SetandoSexo();
                    DataBaseArrays.ArrayPets.add(new Pets(Nome,Raca,idade,Especie,CPF,Sexo));
                    LeitorEEscritor.Escrever(Path,DataBaseArrays.ArrayPets , new PetsCodec(), true);
                    carregarTabela();
                    limparCampos();
                    HabilitarBotao(false);
                    HabilitarCampos(false);
                }
                else if(Tipo.equals("editar")){
                    int linha = TabelaPets.getSelectedRow();
                    if(linha != -1){
                        String Nome = NomeTextField.getText().trim();
                        String CPF = CPFTextField.getText().trim();
                        int idade = Integer.parseInt(IdadeTextField.getText().trim());
                        String Raca = RacaTextField.getText().trim();
                        String Especie = (String) EspecieComboBox.getSelectedItem();
                        String Sexo = SetandoSexo();
                        DataBaseArrays.ArrayPets.set(linha, new Pets(Nome,Raca,idade,Especie,CPF,Sexo));
                        LeitorEEscritor.Escrever(Path,DataBaseArrays.ArrayPets , new PetsCodec(), false);
                        carregarTabela();
                        limparCampos();
                        HabilitarCampos(false);
                        HabilitarBotao(false);
                    }
                    else{
                        JOptionPane.showMessageDialog(null,"Selecione uma linha para editar!", "Selecione uma linha",JOptionPane.WARNING_MESSAGE);
                    }
                }
            
            } 
        }catch(java.lang.NumberFormatException e){
            JOptionPane.showMessageDialog(null,"Digite um numero na idade!","ERROR: Caracter Invalido",JOptionPane.WARNING_MESSAGE);
        }// TODO add your handling code here:
    }//GEN-LAST:event_SalvarButtonActionPerformed

    private void TabelaPetsMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TabelaPetsMouseClicked
        int linha = TabelaPets.getSelectedRow();
        if (linha != -1) {
            NomeTextField.setText(TabelaPets.getValueAt(linha, 0).toString());
            RacaTextField.setText(TabelaPets.getValueAt(linha, 1).toString());
            IdadeTextField.setText(TabelaPets.getValueAt(linha, 2).toString());
            EspecieComboBox.setSelectedIndex(SelecionarEspecie(TabelaPets.getValueAt(linha,3).toString()));
            CPFTextField.setText(TabelaPets.getValueAt(linha, 4).toString());
            SelecionarSexo(TabelaPets.getValueAt(linha, 5).toString());
        }        // TODO add your handling code here:
    }//GEN-LAST:event_TabelaPetsMouseClicked

    
