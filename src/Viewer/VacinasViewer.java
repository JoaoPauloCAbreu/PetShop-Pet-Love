    private void ExcluirButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ExcluirButtonActionPerformed
        int linha = TabelaVacina.getSelectedRow();
        int Confirmacao = JOptionPane.showConfirmDialog(null, "Deseja Excluir?","Confirmação",JOptionPane.YES_NO_OPTION);
        if(Confirmacao == JOptionPane.YES_OPTION){
            DefaultTableModel model = (DefaultTableModel) TabelaVacina.getModel();
            DataBaseArrays.ArrayVacina.remove(linha);
            model.removeRow(linha);
            LeitorEEscritor.Escrever(Path, DataBaseArrays.ArrayVacina, new VacinaCodec(), false);
            limparCampos();  // TODO add your handling code here:
        }
    }//GEN-LAST:event_ExcluirButtonActionPerformed

    private void SalvarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SalvarButtonActionPerformed
        try{
            if(CodigoTextField.getText().trim().isEmpty() || ValorTextField.getText().trim().isEmpty() || CodigoTextField.getText().trim().isEmpty() || TipoComboBox.getSelectedIndex() == -1 || QuantidadeTextField.getText().trim().isEmpty()){
                JOptionPane.showMessageDialog(null,"Campos Vazio, digite algo!", "Campos Vazios",JOptionPane.WARNING_MESSAGE);
            }
            else{
            
                if(Tipo.equals("novo")){
                    int Codigo = Integer.parseInt(CodigoTextField.getText().trim());
                    String Nome = NomeTextField.getText().trim();
                    Double Valor =  Double.valueOf(ValorTextField.getText().trim());
                    String TipoProduto = (String) TipoComboBox.getSelectedItem();
                    int Quantidade = Integer.parseInt(QuantidadeTextField.getText().trim());
                    String Data = DataTextField.getText().trim();
                    DataBaseArrays.ArrayVacina.add(new Vacina(Codigo,Nome,TipoProduto,Valor,Quantidade,Data));
                    LeitorEEscritor.Escrever(Path,DataBaseArrays.ArrayVacina , new VacinaCodec(), true);
                    carregarTabela();
                    limparCampos();
                    HabilitarBotao(false);
                    HabilitarCampos(false);
                }
                else if(Tipo.equals("editar")){
                    int linha = TabelaVacina.getSelectedRow();
                    if(linha != -1){
                        int Codigo = Integer.parseInt(CodigoTextField.getText().trim());
                        String Nome = NomeTextField.getText().trim();
                        Double Valor =  Double.valueOf(ValorTextField.getText().trim());
                        String TipoProduto = (String) TipoComboBox.getSelectedItem();
                        int Quantidade = Integer.parseInt(QuantidadeTextField.getText());
                        String Data = DataTextField.getText();
                        DataBaseArrays.ArrayVacina.set(linha, new Vacina(Codigo,Nome,TipoProduto,Valor,Quantidade,Data));
                        LeitorEEscritor.Escrever(Path,DataBaseArrays.ArrayVacina , new VacinaCodec(), false);
                        carregarTabela();
                        limparCampos();
                        HabilitarCampos(false);
                        HabilitarBotao(false);
                    }
                    else{
                        JOptionPane.showMessageDialog(null,"Selecione uma linha para editar!", "Selecione uma linha",JOptionPane.WARNING_MESSAGE);
                    }
                }
            
            } 
        }catch(java.lang.NumberFormatException e){
            JOptionPane.showMessageDialog(null,"Digite um numero válido!","ERROR: Caracter Invalido",JOptionPane.WARNING_MESSAGE);
        }// TODO add your handling code here:
    }//GEN-LAST:event_SalvarButtonActionPerformed

    private void TabelaVacinaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TabelaVacinaMouseClicked
        int linha = TabelaVacina.getSelectedRow();
        if (linha != -1) {
            CodigoTextField.setText(TabelaVacina.getValueAt(linha, 0).toString());
            NomeTextField.setText(TabelaVacina.getValueAt(linha, 1).toString());
            TipoComboBox.setSelectedIndex(SelecionarEspecie(TabelaVacina.getValueAt(linha,2).toString()));
            ValorTextField.setText(TabelaVacina.getValueAt(linha, 3).toString());
            QuantidadeTextField.setText(TabelaVacina.getValueAt(linha, 4).toString());
            DataTextField.setText(TabelaVacina.getValueAt(linha, 5).toString());
            
        }        // TODO add your handling code here:
    }//GEN-LAST:event_TabelaVacinaMouseClicked

