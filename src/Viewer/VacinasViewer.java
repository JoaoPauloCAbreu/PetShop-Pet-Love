    private void limparCampos(){
        CodigoTextField.setText("");
        NomeTextField.setText("");
        ValorTextField.setText("");
        TipoComboBox.setSelectedIndex(-1);
        QuantidadeTextField.setText("");
        DataTextField.setText("");
    }
    
    private void HabilitarBotao(boolean a){
        SalvarButton.setVisible(a);
        CancelarButton.setVisible(a);
        NovoButton.setVisible(!a);
        EditarButton.setVisible(!a);
        ExcluirButton.setVisible(!a);
        
    }
    
    private void HabilitarCampos(boolean a){
    CodigoTextField.setEnabled(a);
    NomeTextField.setEnabled(a);
    ValorTextField.setEnabled(a);
    TipoComboBox.setEnabled(a);
    QuantidadeTextField.setEnabled(a);
    DataTextField.setEnabled(a);
    }
    
    private void carregarTabela() {
    DefaultTableModel model = (DefaultTableModel) TabelaVacina.getModel();
    model.setRowCount(0); 

    for (Vacina c : DataBaseArrays.ArrayVacina) {
        model.addRow(new Object[]{
            c.getCodigo(),
            c.getNome(),
            c.getTipo(),
            c.getValor(),
            c.getQuantidade(),
            c.getData()
            
        });
    }
}
    
    private int SelecionarEspecie(String a){
    if(a.equals("Zoetis")){
        return 0;
    }
    else if(a.equals("Ourofino")){
        return 1;
    }
    else if(a.equals("Boehringer Ingelheim")){
        return 2;
    }
    else{
        return 3;
    }
    
    }
    
  
    
    

