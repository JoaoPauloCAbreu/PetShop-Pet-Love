    private boolean ValidarSenha(String Usuario,String Senha){
        
        LeitorEEscritor.Ler(Path, new UsuariosCodec());
        for(Usuario u : LeitorEEscritor.Ler(Path, new UsuariosCodec()) ){
            if(u.getLoginUsuario().toLowerCase().equals(Usuario)  && u.getLoginSenha().equals(Senha)){
                return true;
            }
        }
        return false;
    }
    
    
    
