    private void EntrarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EntrarButtonActionPerformed
        if(UsuarioTextField.getText().isEmpty() || PasswordTextField.getText().isEmpty()){
            JOptionPane.showMessageDialog(null, "Campos Vazios: Insira seu login ","Login Vazio",JOptionPane.ERROR_MESSAGE);
            
        }
        else if(ValidarSenha(UsuarioTextField.getText().toLowerCase(),PasswordTextField.getText()) == true){
            this.dispose();
            MenuJframe Menu = new MenuJframe();
            Menu.setLocationRelativeTo(null);
            Menu.setVisible(true);
        }
        else{
            UsuarioTextField.setText("");
            PasswordTextField.setText("");
            JOptionPane.showMessageDialog(null, "Senha incorreta: Tente Novamente","Login Incorreto",JOptionPane.ERROR_MESSAGE);
        }
       
    }//GEN-LAST:event_EntrarButtonActionPerformed

